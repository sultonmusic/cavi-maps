async function build() {
  const lines = []
  for (const name of POI_ICON_NAMES) {
    const { s, f } = await glyph(name)
    const parts = [`s:${JSON.stringify(s)}`]
    if (f?.length) parts.push(`f:${JSON.stringify(f)}`)
    lines.push(`  ${JSON.stringify(name)}: { ${parts.join(', ')} },`)
  }
  return `${licence()}export const GLYPH_SOURCE = ${JSON.stringify(`lucide-react ${version}`)}\n\nexport const GLYPHS = {\n${lines.join('\n')}\n}\n`
}

const same = (a, b) => process.platform === 'win32' ? a.toLowerCase() === b.toLowerCase() : a === b
if (process.argv[1] && same(resolve(process.argv[1]), fileURLToPath(import.meta.url))) {
  const text = await build()
  if (process.argv.includes('--check')) {
    let current = ''
    try { current = readFileSync(target, 'utf8') } catch { /* missing counts as stale */ }
    if (current !== text) {
      console.error('lib/poi-glyphs.mjs is out of date: run node scripts/build-poi-glyphs.mjs')
      process.exit(1)
    }
    console.log(`PASS: lib/poi-glyphs.mjs matches lucide-react ${version} and the icon tables (${POI_ICON_NAMES.length} glyphs).`)
  } else {
    writeFileSync(target, text)
    console.log(`Wrote lib/poi-glyphs.mjs: ${POI_ICON_NAMES.length} glyphs from lucide-react ${version}, ${(Buffer.byteLength(text) / 1024).toFixed(1)} KB.`)
  }
}
