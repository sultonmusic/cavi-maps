/* The white pictograms drawn on the map's place discs, as plain SVG path data.
 *
 *   node scripts/build-poi-glyphs.mjs           writes lib/poi-glyphs.mjs
 *   node scripts/build-poi-glyphs.mjs --check   fails if lib/poi-glyphs.mjs is out of date
 *
 * Re-run after changing the icon tables in lib/poi-icons.mjs. The icons come from the installed
 * lucide-react (24×24, stroked, round caps); every shape is turned into one path string so the map
 * can draw it with Path2D and the page with <path>. The written module has no runtime dependency on
 * lucide, so the map keeps working offline and across lucide upgrades. */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { POI_ICON_NAMES } from '../lib/poi-icons.mjs'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const target = resolve(root, 'lib/poi-glyphs.mjs')
const lucide = resolve(root, 'node_modules/lucide-react')
const version = JSON.parse(readFileSync(resolve(lucide, 'package.json'), 'utf8')).version

/** Pictograms lucide does not have, in the same 24-unit stroked style. */
const CUSTOM = {
  tooth: { s: ['M7.5 3C5 3 3 5 3 7.6c0 1.9.7 3.1 1.3 4.7.6 1.7.7 4 1.3 6.4.4 1.5 1.1 2.3 1.9 2.3 1.4 0 1.7-2.4 2.2-4.4.3-1.1.8-1.8 2.3-1.8s2 .7 2.3 1.8c.5 2 .8 4.4 2.2 4.4.8 0 1.5-.8 1.9-2.3.6-2.4.7-4.7 1.3-6.4.6-1.6 1.3-2.8 1.3-4.7C21 5 19 3 16.5 3c-1.9 0-2.9 1-4.5 1S9.4 3 7.5 3z'] },
}

const n = value => {
  const number = Number(value)
  if (!Number.isFinite(number)) throw new Error(`not a number: ${value}`)
  return String(+number.toFixed(3))
}
const num = (attrs, key, fallback) => attrs[key] === undefined ? fallback : Number(attrs[key])

/** One SVG element of a lucide icon as a path string. */
export function toPath(tag, attrs) {
  switch (tag) {
    case 'path': return String(attrs.d).trim()
    case 'circle': case 'ellipse': {
      const cx = num(attrs, 'cx', 0), cy = num(attrs, 'cy', 0)
      const rx = tag === 'circle' ? num(attrs, 'r', 0) : num(attrs, 'rx', 0), ry = tag === 'circle' ? rx : num(attrs, 'ry', 0)
      return `M${n(cx - rx)} ${n(cy)}a${n(rx)} ${n(ry)} 0 1 0 ${n(2 * rx)} 0a${n(rx)} ${n(ry)} 0 1 0 ${n(-2 * rx)} 0Z`
    }
    case 'line': return `M${n(attrs.x1)} ${n(attrs.y1)}L${n(attrs.x2)} ${n(attrs.y2)}`
    case 'polyline': case 'polygon': {
      const values = String(attrs.points).trim().split(/[\s,]+/).map(Number)
      if (values.length < 4 || values.length % 2) throw new Error(`bad points: ${attrs.points}`)
      let d = `M${n(values[0])} ${n(values[1])}`
      for (let i = 2; i < values.length; i += 2) d += `L${n(values[i])} ${n(values[i + 1])}`
      return tag === 'polygon' ? d + 'Z' : d
    }
    case 'rect': {
      const x = num(attrs, 'x', 0), y = num(attrs, 'y', 0), w = num(attrs, 'width', 0), h = num(attrs, 'height', 0)
      const r = Math.max(0, Math.min(num(attrs, 'rx', undefined) ?? num(attrs, 'ry', 0), w / 2, h / 2))
      if (!r) return `M${n(x)} ${n(y)}h${n(w)}v${n(h)}h${n(-w)}Z`
      const arc = (dx, dy) => `a${n(r)} ${n(r)} 0 0 1 ${n(dx)} ${n(dy)}`
      return `M${n(x + r)} ${n(y)}h${n(w - 2 * r)}${arc(r, r)}v${n(h - 2 * r)}${arc(-r, r)}h${n(-(w - 2 * r))}${arc(-r, -r)}v${n(-(h - 2 * r))}${arc(r, -r)}Z`
    }
    default: throw new Error(`unsupported SVG element <${tag}>`)
  }
}

/** One icon's stroked and filled paths. */
async function glyph(name) {
  if (CUSTOM[name]) return CUSTOM[name]
  const file = resolve(lucide, 'dist/esm/icons', `${name}.mjs`)
  let nodes
  try {
    ({ __iconNode: nodes } = await import(pathToFileURL(file).href))
  } catch (error) {
    throw new Error(`lucide-react ${version} has no icon "${name}" (${file}): ${error.message}`)
  }
  if (!Array.isArray(nodes) || !nodes.length) throw new Error(`icon "${name}" has no shapes`)
  const s = [], f = []
  for (const [tag, attrs] of nodes) (attrs.fill && attrs.fill !== 'none' ? f : s).push(toPath(tag, attrs))
  return f.length ? { s, f } : { s }
}

